/**
 * Bundles Zyte's AI-extraction output schemas (Product, Article, JobPosting…) from
 * spec/zyte-openapi.json into self-contained JSON Schemas for LLM prompts: $refs inlined,
 * descriptions cut to their first sentence, examples dropped, and `metadata` removed (xyte fills
 * it). Writes src/schemas.gen.ts.
 */
const spec = await Bun.file('spec/zyte-openapi.json').json();
const schemas: Record<string, unknown> = spec.components.schemas;

const OUTPUTS: Record<string, string> = {
  product: 'Product',
  productList: 'ProductList',
  productNavigation: 'ProductNavigation',
  article: 'Article',
  articleList: 'ArticleList',
  articleNavigation: 'ArticleNavigation',
  forumThread: 'ForumThread',
  jobPosting: 'JobPosting',
  jobPostingNavigation: 'JobPostingNavigation',
  pageContent: 'PageContent',
  serp: 'Serp',
};

const KEEP = new Set(['type', 'properties', 'items', 'enum', 'format', 'required', 'description', 'nullable', 'additionalProperties']);

function firstSentence(text: string): string {
  const clean = text
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1') // markdown links → text
    .replace(/\s+/g, ' ')
    .trim();
  const sentence = /^.*?[.!?](\s|$)/.exec(clean)?.[0]?.trim() ?? clean;
  return sentence.length > 220 ? `${sentence.slice(0, 217)}…` : sentence;
}

function resolve(node: unknown, seen: string[] = []): unknown {
  if (Array.isArray(node)) return node.map((n) => resolve(n, seen));
  if (node == null || typeof node !== 'object') return node;
  const obj = node as Record<string, unknown>;

  if (typeof obj.$ref === 'string') {
    const name = obj.$ref.split('/').at(-1)!;
    if (seen.includes(name)) return { type: 'object', description: `(recursive ${name})` };
    return resolve(schemas[name], [...seen, name]);
  }
  // allOf: merge parts (Zyte uses it to attach descriptions to $refs).
  if (Array.isArray(obj.allOf)) {
    const merged: Record<string, unknown> = {};
    for (const part of obj.allOf.map((p) => resolve(p, seen)) as Record<string, unknown>[]) {
      for (const [k, v] of Object.entries(part)) {
        if (k === 'properties') merged.properties = { ...(merged.properties as object), ...(v as object) };
        else if (k === 'required') merged.required = [...new Set([...((merged.required as string[]) ?? []), ...(v as string[])])];
        else merged[k] ??= v;
      }
    }
    const rest = Object.fromEntries(Object.entries(obj).filter(([k]) => k !== 'allOf'));
    return clean({ ...merged, ...resolve(rest, seen) as object });
  }
  if (Array.isArray(obj.oneOf) || Array.isArray(obj.anyOf)) {
    // Prompts don't need alternatives: keep the first branch.
    const first = (obj.oneOf ?? obj.anyOf) as unknown[];
    return resolve({ ...obj, oneOf: undefined, anyOf: undefined, ...(resolve(first[0], seen) as object) }, seen);
  }
  return clean(Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, k === 'properties' ? mapValues(v as object, seen) : resolve(v, seen)])));
}

function mapValues(props: object, seen: string[]): object {
  return Object.fromEntries(Object.entries(props).map(([k, v]) => [k, resolve(v, seen)]));
}

function clean(obj: Record<string, unknown>): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(obj)) {
    if (!KEEP.has(k) || v === undefined) continue;
    out[k] = k === 'description' && typeof v === 'string' ? firstSentence(v) : v;
  }
  return out;
}

const bundled: Record<string, unknown> = {};
for (const [field, name] of Object.entries(OUTPUTS)) {
  const schema = resolve({ $ref: `#/components/schemas/${name}` }) as { properties?: Record<string, unknown>; required?: string[] };
  delete schema.properties?.metadata;
  if (schema.required) schema.required = schema.required.filter((r) => r !== 'metadata');
  bundled[field] = schema;
}

const body = JSON.stringify(bundled, null, 2);
await Bun.write(
  'src/schemas.gen.ts',
  `// Generated by \`bun scripts/gen-schemas.ts\` from spec/zyte-openapi.json. Do not edit.\n` +
    `// Zyte AI-extraction output schemas, bundled for LLM prompts.\n\n` +
    `export type OutputSchemaField =\n${Object.keys(OUTPUTS).map((f) => `  | '${f}'`).join('\n')};\n\n` +
    `export const OUTPUT_SCHEMAS: Record<OutputSchemaField, object> = ${body};\n`,
);
console.log(`wrote src/schemas.gen.ts (${(body.length / 1024).toFixed(0)} KB)`);
